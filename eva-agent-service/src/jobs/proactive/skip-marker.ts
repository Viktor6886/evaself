/**
 * Слово, которым модель отказывается от проактивного сообщения.
 *
 * Историческое, знакомо промптам: heartbeat, утренний и вечерний
 * check-in просят ответить им, если повода писать нет.
 *
 * Проверка была на точное равенство — и этого мало. Модель отвечает
 * текстом, а текст она оформляет: «HEARTBEAT_SKIP.», «**HEARTBEAT_SKIP**»,
 * «HEARTBEAT_SKIP — повода нет» равенству не удовлетворяют, и служебное
 * слово уходило человеку в чат как обычное сообщение. Оно там и
 * появилось на боевой установке.
 *
 * Поэтому достаточно упоминания: сообщение, в котором вообще есть этот
 * маркер, человеку не отправляется. Цена ошибки несимметрична —
 * пропущенный выход на связь стоит следующего окна через несколько
 * часов, а служебное слово в чате стоит доверия к собеседнику. Модель,
 * написавшая маркер посреди настоящего сообщения, противоречит сама
 * себе, и угадывать за неё продукт не должен.
 */
export const SKIP_MARKER = "HEARTBEAT_SKIP";

/** Отказалась ли модель писать. Пустой ответ — тоже отказ. */
export function isSkipReply(reply: string): boolean {
  return reply.trim() === "" || reply.includes(SKIP_MARKER);
}
