/**
 * Сколько контекста Letta имеет право держать в conversation.
 *
 * Контекста, а не истории. Число уходит в App Server как
 * `context_window_limit` — «the context window limit used by the agent», —
 * и Letta меряет им ВЕСЬ собранный вход: системный промпт, персону, блоки
 * памяти, описания инструментов и только потом сообщения. Эта разница
 * стоила живого отказа: константу назвали «бюджетом истории», префикс
 * съел из неё половину, и Ева стала сжимать почти каждый ход.
 *
 * Продукт знает предел модели — он лежит в `llm_providers.context_window`
 * и им же роутер отвергает слишком большой запрос. Letta об этом пределе
 * не знала: `default_context_window` по умолчанию `NULL`, и в App Server
 * не уходило ничего. Сжимать историю ей было не по чему.
 *
 * Чем это кончается, видно на боевой установке: диалог дорос до 770 000
 * токенов, роутер честно ответил «не помещается в 256000» — и с этого
 * момента ЛЮБОЕ сообщение, включая «привет», получало отказ. Диалог
 * умирает не постепенно, а разом и навсегда: сжаться сам он уже не может,
 * потому что для сжатия тоже нужен ход.
 *
 * Предел берётся по САМОЙ СЛАБОЙ модели включённой цепочки, а не по
 * активной: аварийный резерв обязан принять тот же разговор, иначе он не
 * резерв. Из предела вычитается ответ модели и запас на постоянную часть
 * входа.
 */

/** Профиль провайдера в части, относящейся к размеру запроса. */
export interface ContextProfile {
  context_window: number;
  max_output_tokens: number;
}

/**
 * Что занимает ход помимо самих сообщений: системный промпт, персона,
 * описания инструментов и продуктовый контекст. На боевой установке это
 * около ста килобайт постоянного префикса — порядка тридцати тысяч
 * токенов; запас взят с превышением, потому что ошибка в эту сторону
 * стоит одного лишнего сжатия, а в обратную — мёртвого диалога.
 *
 * Это ОЦЕНКА с запасом, а не измерение. Настоящий размер префикса
 * показывает `GET /v1/canonical-context`, а его цену в токенах —
 * `make check-tokens`. Ничто в коде эти числа не сверяет: если персона,
 * блоки или состав инструментов вырастут за сорок тысяч, узнать об этом
 * можно только измерением.
 */
export const CONTEXT_RESERVE_TOKENS = 40_000;

/**
 * Ниже этого предела ужимать бессмысленно: разговор перестанет помещаться
 * сам в себя. Модель с таким окном просто не годится для Евы, и решать
 * это подбором предела нельзя.
 */
export const MIN_CONTEXT_WINDOW = 8_000;

/**
 * Предел безопасности для Letta: сколько всего физически примет самая
 * слабая включённая модель. `null` — включённых провайдеров нет, и
 * говорить не о чем: выдумывать число вместо факта хуже, чем не сказать
 * ничего.
 */
export function safeContextWindow(providers: readonly ContextProfile[]): number | null {
  const usable = providers.filter((item) => Number.isFinite(item.context_window)
    && item.context_window > 0);
  if (usable.length === 0) return null;

  const weakest = Math.min(...usable.map((item) => item.context_window));
  const output = Math.max(...usable.map((item) => Math.max(0, item.max_output_tokens || 0)));
  const limit = weakest - output - CONTEXT_RESERVE_TOKENS;

  // У маленькой модели вычет съедает всё окно. Отдаём долю от него: это
  // всё равно предел, по которому Letta сожмёт историю, а без предела она
  // не сожмёт её вовсе.
  if (limit < MIN_CONTEXT_WINDOW) {
    const share = Math.floor(weakest * 0.5);
    return share >= MIN_CONTEXT_WINDOW ? share : null;
  }
  return limit;
}

/**
 * Сколько контекста мы согласны оплачивать в каждом шаге.
 *
 * `safeContextWindow` отвечает на вопрос «сколько влезет, чтобы диалог не
 * умер». Это предел безопасности, и как бюджет он никуда не годится: на
 * модели с окном 256 000 он разрешает контексту дорасти до двухсот тысяч
 * токенов — и ровно столько отправляется заново в КАЖДОМ шаге КАЖДОГО
 * хода. Ход с поиском и двумя чтениями страниц платит за них четыре раза.
 *
 * Число считается ЦЕЛИКОМ, вместе с постоянным префиксом. Это не
 * тонкость, а причина отказа: Letta получает его как
 * `context_window_limit` — «the context window limit used by the agent», —
 * и меряет им весь собранный контекст. Первая версия этой константы
 * называлась «бюджет истории» и стояла на 60 000: префикс съедал из них
 * тридцать тысяч, разговору доставалось тридцать вместо прежних ста
 * семидесяти, и Letta принималась сжимать историю почти каждый ход.
 * Сжатие — это обращение к модели ВНУТРИ хода, да ещё и событие, на
 * котором заводится рефлексия (`dreaming.trigger = compaction-event`).
 * Человек это увидел просто: Ева стала подолгу думать перед ответом.
 *
 * Отсюда сто тысяч: около тридцати занимает постоянный префикс —
 * системный промпт, персона, блоки памяти, описания инструментов, — и
 * около семидесяти остаётся разговору. Против прежних ста семидесяти это
 * вдвое дешевле, а сжатие остаётся редким.
 *
 * Это первое число, которое стоит подбирать по факту: `make check-tokens`
 * показывает и настоящий префикс, и во что обходится ход.
 *
 * Потеря разговора отсюда не следует: долговременная память Евы живёт в
 * memory blocks и MemFS, а не в длине ленты сообщений. Сжатие ведёт
 * Letta, и продукт в него не вмешивается.
 */
export const CONTEXT_BUDGET_TOKENS = 100_000;

/**
 * Предел контекста для Letta: бюджет, но никогда не больше безопасного.
 *
 * Обе величины здесь — полное окно, а не история: сравнивать бюджет с
 * пределом безопасности можно только в одних единицах, и разошедшиеся
 * единицы уже стоили одного отказа.
 *
 * Бюджет только ОПУСКАЕТ предел. Поднять его выше того, что модель
 * физически принимает, он не может: тогда вернулась бы та самая смерть
 * диалога, ради которой предел и появился.
 *
 * `null` — включённых провайдеров нет, и считать не из чего.
 */
export function contextLimit(
  providers: readonly ContextProfile[],
  budget = CONTEXT_BUDGET_TOKENS,
): number | null {
  const safe = safeContextWindow(providers);
  if (safe === null) return null;
  return Math.max(Math.min(safe, budget), MIN_CONTEXT_WINDOW);
}
