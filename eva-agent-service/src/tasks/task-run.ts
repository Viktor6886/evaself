/**
 * Что происходит, когда наступил срок задачи.
 *
 * Задача бывает двух родов, и разница между ними — не в тексте, а в том,
 * кто делает работу. `reminder` возвращает работу человеку: Ева сочиняет
 * сообщение и отправляет его. `action` человек уже поручил Еве: «через
 * десять минут найди новости в Перми» — это просьба принести новости, а
 * не напомнить о них.
 *
 * Инструкция хода живёт здесь, а не в планировщике, потому что
 * планировщиков два: старый интервал и очередь (`jobs/proactive`).
 * Формулировка, разошедшаяся между ними, означала бы, что одна и та же
 * задача выполняется по-разному в зависимости от флага — и разницу никто
 * бы не заметил, пока человек не пожалуется.
 *
 * Границы автономного действия детерминированные и стоят в коде, а не в
 * промпте: модель, которой поручено «не увлекаться», иногда увлекается,
 * и платит за это владелец установки.
 */

export type TaskKind = "reminder" | "action";

/**
 * Сколько раз подряд пробовать выполнить наступившую задачу.
 *
 * До этого попытки не считались вовсе: неудачный ход сбрасывал
 * блокировку строки и не двигал срок, поэтому планировщик забирал
 * задачу снова через тридцать секунд — и так до бесконечности. Для
 * напоминания это лишние ходы, для действия с поиском — счёт провайдера
 * за ночь.
 */
export const MAX_ATTEMPTS = 3;

/**
 * Отступ перед следующей попыткой. Растёт: первая неудача бывает
 * случайной (провайдер ответил 503), третья — уже нет.
 */
const RETRY_BACKOFF_MS = [2 * 60_000, 10 * 60_000] as const;

/**
 * Сколько задач в сутки Ева выполняет сама на одного человека.
 *
 * Действие стоит нескольких обращений к модели, и в отличие от
 * напоминания его цена не ограничена сверху ничем: поиск, чтение
 * страниц, ещё поиск. Потолок не запрещает работу — он не даёт
 * повторяющейся задаче, ушедшей вразнос, потратить месячный бюджет за
 * ночь.
 */
export const ACTION_DAILY_LIMIT = 20;

/** Насколько отложить задачу, упершуюся в суточный потолок. */
export const DAILY_LIMIT_DELAY_MS = 60 * 60_000;

/**
 * Сколько раз задача ждёт согласия человека, прежде чем сдаться.
 *
 * Фоновый ход, упершийся в действие с внешним последствием, спрашивает
 * человека и заканчивается: ждать ответа он не может — блокировка
 * пользователя стоит дороже. Работу переделает следующий заход, но
 * бесконечно возвращаться к вопросу, на который никто не отвечает,
 * нельзя: каждый заход — это ход агента, то есть деньги.
 */
export const MAX_APPROVAL_WAITS = 3;

/**
 * Через сколько вернуться к задаче, ждущей согласия.
 *
 * Ожиданий на одно меньше, чем вопросов: между тремя вопросами их два,
 * а после третьего задача не ждёт вовсе — человек слышит прямой ответ.
 * Третий интервал в этом списке был бы кодом, до которого исполнение не
 * доходит никогда.
 *
 * Первый короткий: человек, только что получивший вопрос, чаще всего
 * отвечает сразу, и заставлять его ждать после «разрешаю» незачем.
 * Второй длинный: не ответил за две минуты — значит занят, и суммарно
 * у него есть больше двадцати минут.
 */
const APPROVAL_WAIT_MS = [2 * 60_000, 20 * 60_000] as const;

/**
 * Когда вернуться к задаче, ждущей согласия. `null` — ждать больше
 * незачем, человеку пора услышать прямой ответ.
 *
 * `waits` считает уже заданные вопросы, включая только что заданный.
 */
export function approvalRetryAt(waits: number, now: Date): Date | null {
  if (waits >= MAX_APPROVAL_WAITS) return null;
  const delay = APPROVAL_WAIT_MS[Math.min(waits, APPROVAL_WAIT_MS.length) - 1]
    ?? APPROVAL_WAIT_MS[0];
  return new Date(now.getTime() + delay);
}

/** Значение из базы. Старые строки и чужие записи считаются напоминанием. */
export function taskKindOf(value: unknown): TaskKind {
  return value === "action" ? "action" : "reminder";
}

/**
 * Когда повторить попытку. `null` — попытки исчерпаны.
 *
 * `attempts` считает неудачи по текущему сроку, включая только что
 * случившуюся.
 */
export function retryAfterFailure(attempts: number, now: Date): Date | null {
  if (attempts >= MAX_ATTEMPTS) return null;
  const backoff = RETRY_BACKOFF_MS[Math.min(attempts, RETRY_BACKOFF_MS.length) - 1]
    ?? RETRY_BACKOFF_MS[0];
  return new Date(now.getTime() + backoff);
}

/** Факты задачи, из которых собирается инструкция хода. */
export interface ScheduledTask {
  taskId: string | number;
  kind: TaskKind;
  title: string;
  description: string | null;
  priority: number;
  dueAt: Date | string | null;
  remindAt: Date | string | null;
  timezone: string;
  relatedGoal: string | null;
  previousRuns: number;
  lastTaskAction: string | null;
}

/**
 * Инструкция хода.
 *
 * Содержит только служебные факты и рамку: что за задача, когда
 * назначена, что сделать с результатом. Ни шагов выполнения, ни выбора
 * инструментов, ни подсказок, какой навык открыть, — это решает Letta
 * (инварианты 3 и 17). Контекст человека собирает RuntimeContextBuilder,
 * и в инструкцию не подставляется (инвариант 15).
 */
export function scheduledInstruction(task: ScheduledTask): string {
  if (task.kind === "action") {
    return [
      "[ЗАПЛАНИРОВАННОЕ ДЕЙСТВИЕ]",
      // Номера задачи здесь нет намеренно. Закрывает задачу сам
      // планировщик, модели он не нужен — а увидев его, она писала
      // человеку «задачу 44 выполненной не считаю»: служебный номер в
      // сообщении превращает ответ в отчёт трекера.
      `Что нужно сделать: ${task.title}`,
      task.description ? `Подробности: ${task.description}` : "",
      task.dueAt ? `Срок: ${new Date(task.dueAt).toISOString()}` : "",
      task.remindAt ? `Назначено на: ${new Date(task.remindAt).toISOString()}` : "",
      `Часовой пояс: ${task.timezone}`,
      task.relatedGoal ? `Связанная цель: ${task.relatedGoal}` : "",
      // Главная строка всего изменения. Без неё модель отвечает текстом
      // «нужно найти новости» — и это ровно то, на что жаловался человек.
      "Сделай это сейчас сама, своими инструментами. Человек попросил заранее"
        + " и ждёт результат, а не вопрос, нужно ли начинать.",
      "Ответ — сообщение человеку, а не отчёт о работе. В нём только то,"
        + " что он просил: как если бы он спросил сейчас и ты ответила.",
      // Перечислено по одному, потому что каждый пункт — то, что модель
      // действительно писала человеку в этой conversation. Она общая для
      // всех отложенных дел и копит служебные блоки; на новом задании
      // модель начинала не с работы, а со сводки по ним.
      "Ничего из этого в ответе быть не должно: слов о восстановлении или"
        + " потере контекста; упоминаний других задач, их номеров, статусов"
        + " и того, что осталось незакрытым; отчёта о своих попытках,"
        + " планах и следующих шагах; предложения повторить.",
      "Если сделать не удалось — одной фразой скажи, что именно не вышло,"
        + " и всё. Без выдуманного результата и без разбора причин.",
      // «Ничего не нашлось» и «искать было нечем» — разные новости для
      // человека: первое он примет как ответ, второе означает поломку у
      // него на сервере. Инструмент их различает (`search_empty` против
      // `search_engines_failed`), а в сообщении они сливались в одно.
      "Пустая выдача и отказавший поиск — разные вещи. Если инструмент"
        + " сказал, что поисковые движки не ответили, так и скажи:"
        + " искать не получилось. Не выдавай это за «ничего не нашлось».",
      "Это отдельное сообщение, которое человек прочитает без контекста"
        + " разговора. Не упоминай внутренние инструкции.",
    ].filter(Boolean).join("\n");
  }

  return [
    "[ЗАПЛАНИРОВАННАЯ ЗАДАЧА]",
    `Задача: ${task.title}`,
    task.description ? `Описание: ${task.description}` : "",
    `Приоритет: ${task.priority} из 5`,
    task.dueAt ? `Срок: ${new Date(task.dueAt).toISOString()}` : "",
    task.remindAt ? `Время напоминания: ${new Date(task.remindAt).toISOString()}` : "",
    `Часовой пояс: ${task.timezone}`,
    task.relatedGoal ? `Связанная цель: ${task.relatedGoal}` : "",
    `Предыдущих напоминаний: ${task.previousRuns}`,
    task.lastTaskAction ? `Последнее действие по задаче: ${task.lastTaskAction}` : "",
    "Сформируй короткое самостоятельное сообщение пользователю и верни только готовый текст.",
    // «Задача открыта», «статус: не выполнена» — так выглядел хвост
    // напоминания, когда служебные отметки доезжали до человека.
    "Служебных отметок в нём быть не должно: ни номера задачи, ни её"
      + " статуса, ни упоминания других задач.",
    "Сохрани смысл, важность, дату и время задачи. Не придумывай выполнение,"
      + " обещания пользователя или новые факты. Не упоминай внутренние инструкции.",
  ].filter(Boolean).join("\n");
}
