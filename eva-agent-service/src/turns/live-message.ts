/**
 * Ждёт ли человек ответа прямо сейчас.
 *
 * Фоновый ход — выполнение отложенного дела, выход на связь по своей
 * инициативе — держит блокировку пользователя всё время работы. Пока он
 * идёт, живое сообщение стоит в очереди: человек пишет «привет» и не
 * получает ничего, а после третьего сообщения очередь его вовсе
 * отвергает (`UserTurnLock`, `maxQueueDepth`).
 *
 * Поэтому фоновая работа уступает: увидев непринятое входящее, ход
 * останавливается и возвращается позже.
 *
 * Смотреть надо на `telegram_user_id`, а НЕ на `user_id`. При приёме
 * апдейта внутренний пользователь ещё не опознан, и `user_id` в строке
 * пуст — проверка по нему не совпадала никогда, и уступка не работала
 * ни разу с тех пор, как была написана.
 */

import type { Database } from "../db.js";

/**
 * Состояния, в которых сообщение ещё ждёт человека.
 *
 * `processing` включён намеренно: так выглядит сообщение, которое воркер
 * уже забрал и держит перед блокировкой — то есть ровно то, что стоит в
 * очереди за нашим фоновым ходом.
 */
const PENDING = ["queued", "processing", "retry"];

export class LiveMessageWatch {
  constructor(private readonly db: Database) {}

  /**
   * Пришло ли от человека сообщение после `since`.
   *
   * Граница по времени обязательна: строка, застрявшая в `processing` от
   * упавшего воркера, иначе означала бы «человек пишет» вечно, и фоновая
   * работа не выполнилась бы никогда.
   *
   * Отказ запроса уступкой не считается: потерять ход из-за сорванной
   * проверки хуже, чем один раз не уступить.
   */
  async waiting(telegramId: number, since: Date): Promise<boolean> {
    try {
      const { rowCount } = await this.db.query(
        `
          -- tenant: by telegram_user_id — входящие того же человека, чей ход идёт
          SELECT 1 FROM telegram_updates
           WHERE telegram_user_id = $1
             AND status = ANY($2::text[])
             AND received_at >= $3
           LIMIT 1`,
        [telegramId, PENDING, since.toISOString()],
      );
      return (rowCount ?? 0) > 0;
    } catch {
      return false;
    }
  }
}
