import assert from "node:assert/strict";
import { test } from "node:test";

import {
  feminineForm,
  feminizeSelfReference,
  normalizeReplyGender,
} from "../dist/i18n/eva-gender.js";

const fix = (text: string) => feminizeSelfReference(text).text;

test("Ева не оставляет мужской род в частых нерегулярных формах", () => {
  assert.equal(fix("Я устал и замёрз."), "Я устала и замёрзла.");
  assert.equal(fix("Я устал и замерз."), "Я устала и замерзла.");
  assert.equal(fix("Я был вынужден это проверить."), "Я была вынуждена это проверить.");
  assert.equal(fix("Я убеждён, что это верно."), "Я убеждена, что это верно.");
  assert.equal(fix("Я заинтересован в результате."), "Я заинтересована в результате.");
  assert.equal(fix("Я сосредоточен на задаче."), "Я сосредоточена на задаче.");
  assert.equal(fix("Я озадачен результатом."), "Я озадачена результатом.");
  assert.equal(fix("Я впечатлён прогрессом."), "Я впечатлена прогрессом.");
});

test("нерегулярные формы доступны единому выходному барьеру", () => {
  assert.equal(feminineForm("замёрз"), "замёрзла");
  assert.equal(feminineForm("Вынужден"), "Вынуждена");
  assert.equal(
    normalizeReplyGender("Я замёрз, но я готов продолжать.", null).text,
    "Я замёрзла, но я готова продолжать.",
  );
});

test("усиление не меняет цитаты, код и фразы пользователя", () => {
  assert.equal(
    fix("Ты написал: «я замёрз и был вынужден уйти»."),
    "Ты написал: «я замёрз и был вынужден уйти».",
  );
  assert.equal(fix("В коде `я замёрз`."), "В коде `я замёрз`.");
  assert.equal(
    fix("Попробуй сказать: я замёрз и был вынужден уйти."),
    "Попробуй сказать: я замёрз и был вынужден уйти.",
  );
});

test("любой глагол о себе в начале фразы — в женском роде, а не только из списка", () => {
  // Закрытый список коротких реплик не знал «разобрал», и Ева написала
  // человеку «Разобрал запись».
  assert.equal(fix("Разобрал запись. Это рабочее совещание."), "Разобрала запись. Это рабочее совещание.");
  assert.equal(fix("Посмотрел твой план. Составил три варианта."), "Посмотрела твой план. Составила три варианта.");
  assert.equal(fix("1. Проанализировал расписание."), "1. Проанализировала расписание.");
  assert.equal(fix("Понял, сделал, уточнил."), "Поняла, сделала, уточнила.");
  assert.equal(fix("Проверил, всё ли работает."), "Проверила, всё ли работает.");
  assert.equal(fix("Был рад помочь."), "Была рада помочь.");
});

test("однородные сказуемые правятся по всему предложению, чужие — нет", () => {
  assert.equal(fix("Уточнил детали и отправил тебе список."), "Уточнила детали и отправила тебе список.");
  assert.equal(fix("Открыл документ и нашёл ошибку."), "Открыла документ и нашла ошибку.");
  assert.equal(fix("Я разобрал запись и отправил саммари."), "Я разобрала запись и отправила саммари.");
  assert.equal(fix("Я их разобрал и сохранил."), "Я их разобрала и сохранила.");
  assert.equal(fix("Я ему ответил."), "Я ему ответила.");
  // Другая часть предложения — другое подлежащее.
  assert.equal(fix("Разобрал запись, начальник сказал и ушёл."), "Разобрала запись, начальник сказал и ушёл.");
  assert.equal(fix("Разобрал запись, где говорящий настаивал и требовал."), "Разобрала запись, где говорящий настаивал и требовал.");
  assert.equal(fix("Посмотрел план, а он уже изменил его."), "Посмотрела план, а он уже изменил его.");
  assert.equal(fix("Я подумал и решил, что он прав."), "Я подумала и решила, что он прав.");
});

test("общее правило не трогает существительные, обратный порядок и вопросы", () => {
  for (const text of [
    "Прошёл месяц с начала курса.",
    "Пришёл ответ от банка.",
    "Позвонил Иван и спросил про отчёт.",
    "Сделал он всё правильно.",
    "Сигнал пропал.",
    "Канал — это способ связи.",
    "Итог: всё готово.",
    "Отдел закрыт на ремонт.",
    "Павел сказал, что придёт.",
    "Начался новый семестр.",
    "Упал сервер.",
    "Понял?",
    "Стал ли ты спокойнее?",
    "Я знаю, что ты устал и сделал всё что мог.",
    "Ты написал: «разобрал запись».",
    "Скажи ему: я справился сам.",
    // Найдено ревью: топонимы на «-ул» и пересказ слов человека после
    // двоеточия.
    "Стамбул встретил тебя дождём, судя по фото.",
    "Кабул остался в новостях этой недели.",
    "Ты написал мне: я всё понял и записал.",
    "В переписке ты отметил: я уже закрыл вопрос с арендой.",
  ]) {
    assert.equal(fix(text), text, text);
  }
});

test("существительное после глагола о себе не мешает правке", () => {
  // Признак «за словом стоит глагол — значит, слово подлежащее» не должен
  // срабатывать на существительные: «детали», «канал», «материал».
  assert.equal(fix("Открыл канал и изучил материал."), "Открыла канал и изучила материал.");
  assert.equal(fix("Посмотрел сериал, который ты советовал."), "Посмотрела сериал, который ты советовал.");
  // Косвенная речь — «я» здесь сама Ева.
  assert.equal(fix("Ты сказал вчера, что я справился сам."), "Ты сказал вчера, что я справилась сама.");
});

test("существительные и чужие сказуемые рядом с «я» не портятся", () => {
  // Найдено ревью Codex: «его» притяжательное, подлежащее после
  // дополнения, косвенный вопрос с «ли». И старая дыра: слово вплотную
  // за сказуемым правилось, даже если это существительное.
  assert.equal(fix("Я проверил канал."), "Я проверила канал.");
  assert.equal(fix("Я открыл файл и нашёл ошибку."), "Я открыла файл и нашла ошибку.");
  assert.equal(fix("Я его канал проверил."), "Я его канал проверил.");
  assert.equal(fix("Получил ответ пользователь."), "Получил ответ пользователь.");
  assert.equal(fix("Я спросил Ивана, получил ли он письмо."), "Я спросила Ивана, получил ли он письмо.");
  // Нерегулярные формы вплотную за сказуемым по-прежнему правятся.
  assert.equal(fix("Я был вынужден это проверить."), "Я была вынуждена это проверить.");
  assert.equal(fix("Отправил письмо клиенту."), "Отправила письмо клиенту.");
});

test("наречие в начале фразы и вводные после «я» не прячут сказуемое о себе", () => {
  assert.equal(fix("Уточнила детали. Потом написал план на неделю."), "Уточнила детали. Потом написала план на неделю.");
  assert.equal(fix("Также учёл твои пожелания."), "Также учла твои пожелания.");
  assert.equal(fix("Я, если честно, забыл предупредить."), "Я, если честно, забыла предупредить.");
  assert.equal(fix("Я устал и проголодался."), "Я устала и проголодалась.");
  for (const text of ["Потом пришёл ответ от банка.", "Сейчас начался новый семестр.", "Уже прошёл месяц."]) {
    assert.equal(fix(text), text, text);
  }
});
