import assert from "node:assert/strict";
import { test } from "node:test";

import { feminizeSelfReference, normalizeReplyGender } from "../dist/i18n/eva-gender.js";
import { summarizeStream } from "../dist/letta.js";

const cases = [
  ["**Понял**, сейчас проверю.", "**Поняла**, сейчас проверю."],
  ["Я **нашёл** ошибку.", "Я **нашла** ошибку."],
  ["**Я** уже _проверил_ файл.", "**Я** уже _проверила_ файл."],
  ["- Проверил файл.\n  * Сохранил результат.", "- Проверила файл.\n  * Сохранила результат."],
  ["1) Проверил файл.\n2. **Нашёл** ошибку.", "1) Проверила файл.\n2. **Нашла** ошибку."],
  ["### Готов помочь\nЯ уже проверил файл.", "### Готова помочь\nЯ уже проверила файл."],
  ["Пока не уверен, что это верно.", "Пока не уверена, что это верно."],
  ["Да, уже внимательно проверил файл.", "Да, уже внимательно проверила файл."],
  ["Я уже точно всё внимательно проверил.", "Я уже точно всё внимательно проверила."],
  ["Я был бы очень рад помочь.", "Я была бы очень рада помочь."],
  ["Был бы очень рад помочь.", "Была бы очень рада помочь."],
  ["Я могу помочь и готов начать.", "Я могу помочь и готова начать."],
  ["Я буду рад помочь.", "Я буду рада помочь."],
  ["Я поняла тебя и уже записал задачу.", "Я поняла тебя и уже записала задачу."],
  ["Я понял и проверила файл, но не смог его открыть.", "Я поняла и проверила файл, но не смогла его открыть."],
  ["Не уверен, но готов проверить.", "Не уверена, но готова проверить."],
  ["Я ПОНЯЛ. ГОТОВ!", "Я ПОНЯЛА. ГОТОВА!"],
] as const;

for (const [input, expected] of cases) {
  test(`регрессия рода: ${input}`, () => {
    const result = feminizeSelfReference(input);
    assert.equal(result.text, expected);
    assert.ok(result.corrections.length > 0);
    assert.deepEqual(feminizeSelfReference(expected), { text: expected, corrections: [] });
    // Род пользователя не должен вернуть Еву к мужскому роду.
    for (const gender of [null, "masculine", "feminine"] as const) {
      assert.equal(normalizeReplyGender(input, gender).text, expected);
    }
  });
}

test("оформление и вводные не снимают защиту чужой речи и кода", () => {
  for (const input of [
    "> Я понял и записал.\n> Не уверен, но готов.",
    "Он написал: «Я **готов**.\nЯ понял и записал».",
    "Ты написал: я уже точно всё внимательно проверил.",
    "Напиши ему: я уже проверил файл.",
    "```text\nЯ **понял**.\nНе уверен.\n```",
    "~~~text\nЯ понял и записал.\n~~~",
    "Я `понял` и `записал`.",
    "[ссылка](https://example.com/я_понял) и https://example.com/я__понял",
    "я_понял = true; я__понял = true;",
    "Не уверен он в ответе.",
    "Потом уже пришёл ответ от банка.",
    "Я знаю, что он готов и уже написал ответ.",
    "Я вижу хороший результат.",
    "Я вижу план и хороший результат.",
    "Я знаю один способ.",
    "Я знаю правило и один пример.",
    "Я знаю, готов результат или нет.",
    "Я поняла и уже пришёл он.",
    "Я поняла, но не смог ответить пользователь.",
    "Я подумала, не пришёл ли поезд.",
    "Я и Пётр уже всё проверили.",
  ]) {
    assert.deepEqual(feminizeSelfReference(input), { text: input, corrections: [] }, input);
  }
});

test("незакрытые цитаты и код защищены на каждом срезе потока", () => {
  for (const protectedText of [
    "«Я **понял** и записал»",
    '"Я понял и записал"',
    "“Я понял и записал”",
    "`я понял`",
    "``я понял``",
    "```text\nЯ понял и записал.\n```",
    "````text\nЯ понял.\n```\nЯ записал.\n````",
    "~~~text\nЯ понял и записал.\n~~~",
    "> Я понял и записал.",
  ]) {
    for (let end = 1; end <= protectedText.length; end += 1) {
      const prefix = protectedText.slice(0, end);
      assert.equal(feminizeSelfReference(prefix).text, prefix);
    }
  }
  assert.equal(
    feminizeSelfReference("> Я понял.\n\n**Проверил** файл.").text,
    "> Я понял.\n\n**Проверила** файл.",
  );
});

test("общая сборка Letta исправляет размеченный ответ после сборки чанков", () => {
  const summary = summarizeStream([
    { type: "assistant", content: "**Пон", uuid: "reply-1" },
    { type: "assistant", content: "ял**. Я могу помочь и ", uuid: "reply-1" },
    { type: "assistant", content: "готов начать.", uuid: "reply-1" },
    { type: "result", stopReason: "end_turn" },
  ] as never);
  assert.equal(summary.reply, "**Поняла**. Я могу помочь и готова начать.");
  assert.equal(summary.genderCorrections, 2);
});
