test("без «ё» и в «-вёл» правка не портит слово", () => {
  // Модель часто пишет без «ё», а общее «-л → -ла» давало «нашела»,
  // «учела», «пришела»; «-ёл → -ла» — «свла» и «провла».
  for (const [input, expected] of [
    ["Нашел три варианта.", "Нашла три варианта."],
    ["Я нашел ошибку.", "Я нашла ошибку."],
    ["Учел.", "Учла."],
    ["Я учел это.", "Я учла это."],
    ["Прочел твоё письмо.", "Прочла твоё письмо."],
    ["Я пришел к выводу.", "Я пришла к выводу."],
    ["Я свёл всё в таблицу.", "Я свела всё в таблицу."],
    ["Я провел анализ.", "Я провела анализ."],
    ["Я перевёл текст.", "Я перевела текст."],
    ["Счёл нужным предупредить.", "Сочла нужным предупредить."],
  ] as const) {
    assert.equal(feminizeSelfReference(input).text, expected, input);
  }
});

