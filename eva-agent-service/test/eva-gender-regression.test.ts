const cases = [
  ["**Понял**, сейчас проверю.", "**Поняла**, сейчас проверю."],
  ["Я **нашёл** ошибку.", "Я **нашла** ошибку."],
  ["**Я** уже _проверил_ файл.", "**Я** уже _проверила_ файл."],
  ["- Проверил файл.\n  * Сохранил результат.", "- Проверила файл.\n  * Сохранила результат."],
  ["1) Проверил файл.\n2. **Нашёл** ошибку.", "1) Проверила файл.\n2. **Нашла** ошибку."],
  ["### Готов помочь\nЯ уже проверил файл.", "### Готова помочь\nЯ уже проверила файл."],
  ["Пока не уверен, что это верно.", "Пока не уверена, что это верно."],
  ["Да, уже внимательно проверил файл.", "Да, уже внимательно проверила файл."],
  ["Я уже точно всё внимательно проверил.", "Я уже точно всё внимательно проверила."],
  ["Я был бы очень рад помочь.", "Я была бы очень рада помочь."],
  ["Был бы очень рад помочь.", "Была бы очень рада помочь."],
  ["Я могу помочь и готов начать.", "Я могу помочь и готова начать."],
  ["Я буду рад помочь.", "Я буду рада помочь."],
  ["Я поняла тебя и уже записал задачу.", "Я поняла тебя и уже записала задачу."],
  ["Я понял и проверила файл, но не смог его открыть.", "Я поняла и проверила файл, но не смогла его открыть."],
  ["Не уверен, но готов проверить.", "Не уверена, но готова проверить."],
  ["Я ПОНЯЛ. ГОТОВ!", "Я ПОНЯЛА. ГОТОВА!"],
] as const;

for (const [input, expected] of cases) {
  test(`регрессия рода: ${input}`, () => {
    const result = feminizeSelfReference(input);
    assert.equal(result.text, expected);
    assert.ok(result.corrections.length > 0);
    assert.deepEqual(feminizeSelfReference(expected), { text: expected, corrections: [] });
    // Род пользователя не должен вернуть Еву к мужскому роду.
    for (const gender of [null, "masculine", "feminine"] as const) {
      assert.equal(normalizeReplyGender(input, gender).text, expected);
    }
  });
}

