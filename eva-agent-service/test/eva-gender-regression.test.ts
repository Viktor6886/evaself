test("графа документа и глагол с подлежащим после него не правятся", () => {
  // Независимое ревью #421: «Подготовил: Иванов И.И.» — подпись в
  // документе, «Пришел ответ» без «ё» — подлежащее после глагола.
  for (const input of [
    "Создал: Иван Петров",
    "Подготовил: Иванов И.И.",
    "Проверил: И. И. Иванов",
    "Составил: ________",
    "Пришел ответ от банка.",
    "Прошел месяц.",
  ]) {
    assert.deepEqual(feminizeSelfReference(input), { text: input, corrections: [] }, input);
  }
  assert.equal(
    feminizeSelfReference("Записал:\n- встреча завтра в 10:00").text,
    "Записала:\n- встреча завтра в 10:00",
  );
  assert.equal(feminizeSelfReference("Записал: Завтра в 10:00 — врач.").text, "Записала: Завтра в 10:00 — врач.");
});
