test("незакрытые цитаты и код защищены на каждом срезе потока", () => {
  for (const protectedText of [
    "«Я **понял** и записал»",
    '"Я понял и записал"',
    "“Я понял и записал”",
    "`я понял`",
    "``я понял``",
    "```text\nЯ понял и записал.\n```",
    "````text\nЯ понял.\n```\nЯ записал.\n````",
    "~~~text\nЯ понял и записал.\n~~~",
    "> Я понял и записал.",
  ]) {
    for (let end = 1; end <= protectedText.length; end += 1) {
      const prefix = protectedText.slice(0, end);
      assert.equal(feminizeSelfReference(prefix).text, prefix);
    }
  }
  assert.equal(
    feminizeSelfReference("> Я понял.\n\n**Проверил** файл.").text,
    "> Я понял.\n\n**Проверила** файл.",
  );
});

test("общая сборка Letta исправляет размеченный ответ после сборки чанков", () => {
  const summary = summarizeStream([
    { type: "assistant", content: "**Пон", uuid: "reply-1" },
    { type: "assistant", content: "ял**. Я могу помочь и ", uuid: "reply-1" },
    { type: "assistant", content: "готов начать.", uuid: "reply-1" },
    { type: "result", stopReason: "end_turn" },
  ] as never);
  assert.equal(summary.reply, "**Поняла**. Я могу помочь и готова начать.");
  assert.equal(summary.genderCorrections, 2);
});

