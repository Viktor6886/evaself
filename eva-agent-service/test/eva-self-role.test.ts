/**
 * Роль Евы и слова, которые правка рода трогать не должна.
 *
 * «Я — твой помощник» проходил мимо правки: глагола в нём нет. А слова
 * словаря для обращения к человеку правка, наоборот, трогала у самой
 * Евы — «нашла хорошая вариант», «я не женщина и не женщина».
 */
import assert from "node:assert/strict";
import { test } from "node:test";

import { feminizeSelfReference, normalizeReplyGender } from "../dist/i18n/eva-gender.js";
import { t } from "../dist/i18n/index.js";

const fixed = [
  ["Я твой помощник по самопознанию.", "Я твоя помощница по самопознанию."],
  ["Я — твой ИИ-компаньон.", "Я — твоя ИИ-компаньонка."],
  ["Я ваш собеседник и друг.", "Я ваша собеседница и подруга."],
  ["Меня зовут Ева, я твой личный помощник.", "Меня зовут Ева, я твоя личная помощница."],
  ["Я — Ева, твой друг и собеседник.", "Я — Ева, твоя подруга и собеседница."],
  ["Я не психолог, я ИИ-помощник.", "Я не психолог, я ИИ-помощница."],
  ["Я ИИ-компаньон, созданный помогать.", "Я ИИ-компаньонка, созданная помогать."],
  ["Я тебе как друг скажу: отдохни.", "Я тебе как подруга скажу: отдохни."],
  ["Я хороший слушатель.", "Я хорошая слушательница."],
  ["Я — **твой помощник**.", "Я — **твоя помощница**."],
  ["Я ТВОЙ ПОМОЩНИК!", "Я ТВОЯ ПОМОЩНИЦА!"],
  ["Я буду рада быть твоим собеседником и другом.", "Я буду рада быть твоей собеседницей и подругой."],
  ["Буду твоим личным помощником.", "Буду твоей личной помощницей."],
  ["Я хочу быть для тебя надёжным союзником.", "Я хочу быть для тебя надёжной союзницей."],
  // Сказуемые, до которых «я» раньше не доходило.
  ["Я тебя правильно понял?", "Я тебя правильно поняла?"],
  ["Извини, я неправильно понял.", "Извини, я неправильно поняла."],
  ["Я не до конца понял.", "Я не до конца поняла."],
  ["Я недоволен собой.", "Я недовольна собой."],
  ["Я вот что подумал: давай попробуем.", "Я вот что подумала: давай попробуем."],
  ["Я не обучен ставить диагнозы.", "Я не обучена ставить диагнозы."],
  ["Я запрограммирован так.", "Я запрограммирована так."],
  ["Я сам не уверен, но я один справлюсь.", "Я сама не уверена, но я одна справлюсь."],
  ["Я всё сделал сам.", "Я всё сделала сама."],
  ["Я был один.", "Я была одна."],
] as const;

for (const [input, expected] of fixed) {
  test(`роль и сказуемое Евы: ${input}`, () => {
    const result = feminizeSelfReference(input);
    assert.equal(result.text, expected);
    assert.ok(result.corrections.length > 0);
    assert.deepEqual(feminizeSelfReference(expected), { text: expected, corrections: [] });
    for (const gender of [null, "masculine", "feminine"] as const) {
      assert.equal(normalizeReplyGender(input, gender).text, expected);
    }
  });
}

/** Род этих слов задаёт не Ева; до правки они становились женскими. */
const untouched = [
  ["Я нашёл хороший вариант.", "Я нашла хороший вариант."],
  ["Нашёл хороший вариант.", "Нашла хороший вариант."],
  ["Я выбрал один путь.", "Я выбрала один путь."],
  ["Я увидел сам процесс.", "Я увидела сам процесс."],
  ["Я нашёл вариант и хороший план.", "Я нашла вариант и хороший план."],
  ["Я проверила файл и сам код.", "Я проверила файл и сам код."],
  ["Я не мужчина и не женщина, я ИИ.", "Я не мужчина и не женщина, я ИИ."],
  ["Сделал милый подарок.", "Сделала милый подарок."],
] as const;

for (const [input, expected] of untouched) {
  test(`чужое слово за сказуемым Евы не меняет род: ${input}`, () => {
    assert.equal(feminizeSelfReference(input).text, expected);
  });
}

test("роль не правится в чужой речи, обращении и без роли из списка", () => {
  for (const text of [
    "Скажи ему: я твой друг.",
    "Ты написал: «я твой помощник».",
    "Я, друг мой, не могу так.",
    "Я и твой друг решили.",
    "Я спросила твоего друга.",
    "Я не твой психолог и не врач.",
    "Я твой ассистент.",
    "Я хочу, чтобы он стал твоим другом.",
    "Ты можешь быть себе другом.",
    "Он будет твоим наставником.",
    "Мне кажется, он мог бы стать тебе другом.",
    "`я твой помощник`",
  ]) {
    assert.deepEqual(feminizeSelfReference(text), { text, corrections: [] }, text);
  }
});

test("приветствие Евы называет её в женском роде", () => {
  for (const key of ["start", "startFirst"] as const) {
    const text = t("ru", key);
    assert.match(text, /собеседница и помощница/u);
    assert.deepEqual(feminizeSelfReference(text).corrections, [], `${key}: мужской род в статическом тексте`);
  }
});
