-- =====================================================================
-- Разрешение на личные данные по умолчанию включено.
--
-- Флаг задумывался так: оператор решает, каким провайдерам доверить
-- личную переписку. На деле получилось иначе.
--
-- Роутер помечает чувствительным любой запрос без явной обратной пометки
-- (server.ts: sensitive = metadata.sensitive !== false), а вся переписка
-- Евы личная по своей природе — то есть чувствительны все запросы до
-- единого. При умолчании sensitive_data_allowed = false фильтр цепочки
-- отклонял каждого провайдера, и роутер возвращал 503 «провайдеру не
-- разрешены чувствительные данные» на сто процентов трафика. Установка
-- выглядела рабочей — провайдеры настроены, проверка связи проходит, — но
-- Ева не могла ответить ни разу, пока оператор не найдёт неочевидную
-- галочку в редакторе провайдера.
--
-- Это не защита, а ловушка: она не заставляет принять осознанное решение,
-- а вынуждает снять непонятный запрет наугад. Провайдера заводит и
-- активирует сам оператор — это и есть решение о доверии. Поэтому
-- умолчание становится «разрешено», а флаг остаётся, чтобы конкретного
-- провайдера при желании ОГРАНИЧИТЬ.
--
-- Существующие строки тоже переводятся в true: на значении false ничего
-- не работало, так что осознанно полагаться на него никто не мог.
-- =====================================================================

BEGIN;

ALTER TABLE llm_providers
    ALTER COLUMN sensitive_data_allowed SET DEFAULT true;

UPDATE llm_providers
   SET sensitive_data_allowed = true, updated_at = now()
 WHERE NOT sensitive_data_allowed;

INSERT INTO schema_migrations (version) VALUES ('023_sensitive_default')
ON CONFLICT (version) DO NOTHING;

COMMIT;
