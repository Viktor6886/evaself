-- =====================================================================
-- Идентификаторы run Letta в записи хода.
--
-- Шаг 05 сначала заявил, что Agent SDK идентификатора run не отдаёт.
-- Это оказалось неверным: `runId` приходит на сообщениях ассистента,
-- вызовах инструментов и reasoning, а `runIds` — на итоговом сообщении
-- (`@letta-ai/letta-agent-sdk/dist/types.d.ts`). Идентификатор был не
-- недоступен, а выброшен.
--
-- Здесь он перестаёт выбрасываться. Хранение — массив: ход может
-- состоять из нескольких run, и брать первый попавшийся значит терять
-- остальные.
--
-- Чего это НЕ даёт: сверки состояния run на стороне Letta. Read-API по
-- идентификатору есть у `@letta-ai/letta-client`, а он по инварианту 4
-- допускается только как control plane и только после contract-тестов.
-- Это отдельный шаг; здесь сохраняется свидетельство, по которому такая
-- сверка станет возможной.
--
-- Миграция только добавляет столбец. Старый код его не читает и не
-- пишет — forward с ним совместим.
-- =====================================================================

BEGIN;

ALTER TABLE turn_runs
    ADD COLUMN IF NOT EXISTS letta_run_ids text[];

COMMENT ON COLUMN turn_runs.letta_run_ids IS
    'Идентификаторы run из потока Agent SDK. Свидетельство для сверки, не ссылка.';

INSERT INTO schema_migrations (version)
VALUES ('032_turn_run_ids')
ON CONFLICT (version) DO NOTHING;

COMMIT;
