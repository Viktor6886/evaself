-- =====================================================================
-- Владелец хода — обязателен.
--
-- Запись хода без владельца недоступна: адресовать её одним `run_id`
-- граница арендатора не даёт, и снять с неё аренду тоже нечем. Такой
-- ход попадал бы в выборку восстановления каждые тридцать секунд и
-- никогда её не покидал — а поскольку `updated_at` у него не меняется,
-- стоял бы в начале выборки и закрывал бы её собой.
--
-- В коде это уже соблюдается: единственная вставка в `turn_runs`
-- отказывается писать строку, у которой нет ни `user_id`, ни
-- `telegram_user_id`. Здесь соглашение становится ограничением схемы:
-- инвариант, который держится только договорённостью, рано или поздно
-- нарушает новый вызывающий код.
--
-- `NOT VALID` намеренно: ограничение проверяет новые строки и не
-- сканирует существующие. Forward-миграция поэтому не блокирует
-- таблицу и работает со старым кодом — он таких строк и не пишет.
-- =====================================================================

BEGIN;

ALTER TABLE turn_runs
    DROP CONSTRAINT IF EXISTS turn_runs_owner_present;

ALTER TABLE turn_runs
    ADD CONSTRAINT turn_runs_owner_present
    CHECK (user_id IS NOT NULL OR telegram_user_id IS NOT NULL)
    NOT VALID;

INSERT INTO schema_migrations (version)
VALUES ('033_turn_owner_constraint')
ON CONFLICT (version) DO NOTHING;

COMMIT;
