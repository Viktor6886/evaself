-- =====================================================================
-- Фактические вызовы нативных инструментов агента.
--
-- Самоотчёт модели о том, открывала она навык или нет, ничего не
-- подтверждает: это такой же текст, как любой другой её текст. Источник
-- истины — поток SDK, где вызов инструмента приходит отдельным
-- сообщением вместе с идентификатором вызова и run.
--
-- Здесь только метаданные. Ни аргументов, ни содержимого навыка, ни
-- рассуждений, ни текста человека: по строке этой таблицы нельзя
-- восстановить ни реплику, ни память (инвариант 19).
--
-- Отдельная таблица, а не `tool_effects`: тот журнал существует ради
-- идемпотентности побочных действий продуктовых инструментов и ключуется
-- эффектом. Нативный `Skill` побочных действий не производит и через
-- журнал эффектов не проходит — записывать его туда значило бы смешать
-- две разные сущности в одной таблице.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS agent_tool_calls (
    id              bigserial   PRIMARY KEY,
    user_id         bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    conversation_id text,

    -- Имя инструмента как его назвал SDK. Не нормализуется: нормализация
    -- скрыла бы появление нового инструмента.
    tool_name       text        NOT NULL,

    -- Имя навыка — только если аргумент вызова его действительно нёс.
    -- NULL значит «SDK не назвал», а не «навык неизвестен»: додумывать
    -- имя нельзя, иначе телеметрия начнёт подтверждать то, чего не было.
    skill_name      text,

    tool_call_id    text        NOT NULL,
    -- Идентификатор run у Letta — текст, а не uuid: формат задаёт она.
    run_id          text,

    -- Итог по соответствующему tool_result. NULL — результата в потоке
    -- не было: вызов начат, но не завершён в пределах этого хода.
    succeeded       boolean,

    called_at       timestamptz NOT NULL DEFAULT now(),

    -- Один вызов — одна строка. Повторный разбор того же хода (например,
    -- при восстановлении) не создаёт дубликатов.
    UNIQUE (user_id, tool_call_id)
);

COMMENT ON TABLE agent_tool_calls IS
    'Метаданные фактических вызовов нативных инструментов агента. Без содержимого.';

CREATE INDEX IF NOT EXISTS agent_tool_calls_user_idx
    ON agent_tool_calls (user_id, called_at DESC);

-- Отдельный индекс под главный вопрос: открывала ли Ева навыки и какие.
CREATE INDEX IF NOT EXISTS agent_tool_calls_skill_idx
    ON agent_tool_calls (user_id, called_at DESC)
    WHERE skill_name IS NOT NULL;

INSERT INTO schema_migrations(version) VALUES('059_agent_tool_calls') ON CONFLICT DO NOTHING;
COMMIT;
