-- Бесплатный тариф: десять сообщений в сутки вместо тридцати.
--
-- Отмена подписки возвращает человека на бесплатный тариф, и его лимит
-- решает, что значит «без подписки». Тридцать сообщений в сутки — это не
-- проба, а полноценное пользование: владелец отменял подписку и видел,
-- что бот продолжает отвечать как ни в чём не бывало.
--
-- Меняется только значение, которое никто не выбирал.
--
-- Отличить «владелец согласен с тридцатью» от «владелец их не трогал»
-- нечем: строку засеяла миграция 002, и следов правки у неё нет.
-- Поэтому условие — «значение всё ещё то, что засеяла установка».
-- Владелец, поставивший своё число, его сохранит; владелец, никогда не
-- открывавший вкладку тарифов, получит десять. Дальше это его настройка:
-- панель правит её в один тап, и повторно миграция ничего не тронет —
-- после наката значение уже не тридцать.

BEGIN;

UPDATE quotas
   SET limit_value = 10, updated_at = now()
 WHERE plan = 'free'
   AND metric = 'messages'
   AND period = 'day'
   AND limit_value = 30;

INSERT INTO schema_migrations (version)
VALUES ('073_free_plan_daily_messages')
ON CONFLICT DO NOTHING;

COMMIT;
