BEGIN;

-- =====================================================================
-- Отложенное поручение доводится до конца
-- =====================================================================
--
-- «Через десять минут сделай пост для моего телеграм-канала» до сих пор
-- не работало, и не по вине планировщика: публикация — действие с
-- внешним последствием, а фоновый ход получал на него отказ. Причина
-- отказа была верной — ждать подтверждения пятнадцать минут значит
-- держать блокировку пользователя, пока он ждёт ответа на живое
-- сообщение, — но следствие оказалось не тем: человек, который сам
-- попросил сделать дело, слышал в ответ «нужно твоё согласие».
--
-- Развязка: фоновый ход не ждёт и не отказывает молча. Он спрашивает
-- человека и заканчивается; задача переносится и выполняется заново,
-- когда согласие получено. Блокировка при этом не удерживается ни
-- секунды.
--
-- Проверка отсутствия эквивалента (инвариант 20): подтверждения уже
-- живут в `tool_approvals`, а выданные права — в `tool_approval_rules`
-- (миграция 041). Обе таблицы подходят целиком; не хватает одного
-- признака — спрашивал ли ход, у которого не было человека по ту
-- сторону. Без него согласие, данное на фоновое действие, ничем не
-- отличалось бы от согласия в живом разговоре, и повторный заход
-- задачи снова упёрся бы в тот же вопрос.
ALTER TABLE tool_approvals
    ADD COLUMN IF NOT EXISTS unattended boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN tool_approvals.unattended IS
    'Спрашивал фоновый ход: человека по ту сторону не было, и ждать ответа было некому.';

-- Повторный заход задачи не должен спрашивать второй раз о том же
-- действии: человек получил бы три одинаковых вопроса подряд.
CREATE INDEX IF NOT EXISTS tool_approvals_unattended_pending_idx
    ON tool_approvals (conversation_id, tool_name, argument_fingerprint)
 WHERE status = 'pending' AND unattended;

-- Задача, ожидающая согласия, — это не отказ и не выполнение. Событие
-- отдельное: по нему считается, сколько раз мы уже спросили, и после
-- третьего человек слышит прямой ответ вместо четвёртого вопроса.
ALTER TABLE task_events DROP CONSTRAINT IF EXISTS task_events_event_type_check;
ALTER TABLE task_events
    ADD CONSTRAINT task_events_event_type_check CHECK (event_type IN (
        'created', 'updated', 'reminder_generated', 'reminder_sent',
        'delivery_failed', 'user_replied', 'snoozed', 'completed',
        'cancelled', 'reopened', 'action_done', 'action_failed',
        'action_awaiting_approval'
    ));

INSERT INTO schema_migrations (version)
VALUES ('082_background_approvals')
ON CONFLICT DO NOTHING;

COMMIT;
