-- =====================================================================
-- Задача без напоминаний.
--
-- Напоминание срабатывало по `COALESCE(next_run_at, remind_at, due_at)`,
-- и погасить его можно было только вместе с задачей: даже без времени
-- напоминания срок сам приводил к напоминанию. Человек, который хочет
-- оставить задачу в списке, но не получать о ней сообщений, выбирал между
-- шумом и потерей задачи.
--
-- Признак выключает и напоминание (kind=reminder), и выполнение по
-- расписанию (kind=action): оба идут через одну и ту же выборку
-- планировщика. Сроки и время напоминания не стираются — включённый
-- обратно признак возвращает задачу к прежнему расписанию.
--
-- Совместимость со старым кодом: новая колонка со значением по умолчанию,
-- прежние задачи напоминают как раньше.
-- =====================================================================

BEGIN;

ALTER TABLE tasks
    ADD COLUMN IF NOT EXISTS reminders_enabled boolean NOT NULL DEFAULT true;

INSERT INTO schema_migrations (version) VALUES ('093_task_reminders_enabled')
ON CONFLICT (version) DO NOTHING;

COMMIT;
